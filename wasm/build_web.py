#!/usr/bin/env python3
"""
Assemble the Tao web application in `wasm/build/web`.

Copies the page (`wasm/web`), the WebAssembly build of Tao (`wasm/build/tao.js`, `tao.wasm`),
and generates:

- `examples.json`: the Tao examples of `bmad-doc/tao_examples`, to run in the browser.
- `hershey.js`: the Hershey to Unicode table of the quick_plot Cairo backend.

Serve the directory with any static web server, EG `python3 -m http.server -d wasm/build/web`.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
from dataclasses import dataclass
from pathlib import Path
from typing import Self

ROOT = Path(__file__).resolve().parent.parent
WASM = ROOT / "wasm"
EXAMPLES = ROOT / "bmad-doc" / "tao_examples"
HERSHEY_HEADER = ROOT / "sim_utils" / "plot" / "qp_cairo_hershey.h"

MAX_EXAMPLE_FILE_SIZE = 2_000_000


@dataclass
class Example:
    """
    A Tao example directory.

    Attributes
    ----------
    name : str
        Directory name.
    args : str
        Tao startup arguments.
    files : dict[str, str]
        File contents by path relative to the directory.
    """

    name: str
    args: str
    files: dict[str, str]

    @classmethod
    def from_directory(cls, directory: Path) -> Self | None:
        files: dict[str, str] = {}
        for path in sorted(directory.rglob("*")):
            if not path.is_file() or path.stat().st_size > MAX_EXAMPLE_FILE_SIZE:
                continue
            try:
                files[str(path.relative_to(directory))] = path.read_text()
            except UnicodeDecodeError:
                continue
        if "tao.init" in files:
            args = "-init tao.init"
        else:
            lattices = [name for name in files if name.endswith(".bmad")]
            if not lattices:
                return None
            args = f"-lat {lattices[0]}"
        return cls(name=directory.name, args=args, files=files)


def hershey_module() -> str:
    """
    Make the JavaScript module with the Hershey character number to Unicode map.

    Returns
    -------
    str
    """
    pairs = re.findall(r"\{(\d+),(0x[0-9a-fA-F]+)\}", HERSHEY_HEADER.read_text())
    entries = ",".join(
        f"{int(hershey)}:{int(code, 16)}" for hershey, code in pairs if int(code, 16)
    )
    return (
        f"// Generated by wasm/build_web.py from sim_utils/plot/{HERSHEY_HEADER.name}. Do not edit.\n"
        f"export const HERSHEY = {{{entries}}};\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--build-dir", type=Path, default=WASM / "build")
    args = parser.parse_args()

    out = args.build_dir / "web"
    out.mkdir(parents=True, exist_ok=True)
    for path in (WASM / "web").iterdir():
        shutil.copy2(path, out / path.name)
    for name in ("tao.js", "tao.wasm"):
        shutil.copy2(args.build_dir / name, out / name)

    (out / "hershey.js").write_text(hershey_module())

    examples = [
        Example.from_directory(d) for d in sorted(EXAMPLES.iterdir()) if d.is_dir()
    ]
    bundle = {
        e.name: {"args": e.args, "files": e.files} for e in examples if e is not None
    }
    (out / "examples.json").write_text(json.dumps(bundle))

    print(f"Wrote {out} ({len(bundle)} examples)")


if __name__ == "__main__":
    main()
